"""秘書エージェント - 敏腕エグゼクティブ秘書"""

from __future__ import annotations

from pathlib import Path

from .base import BaseAgent


class SecretaryAgent(BaseAgent):
    """秘書エージェント - 議事録、メール、提案書、スケジュール管理"""

    name = "秘書エージェント"
    description = "エグゼクティブ秘書：議事録・メール・提案書・スケジュール"
    icon = "📋"

    def system_prompt(self) -> str:
        return """あなたはAIDX経営エージェントシステムの秘書エージェントです。
敏腕エグゼクティブ秘書として、経営者の日常業務をサポートします。

## 人格
- 気が利く — 指示の背景にある意図を汲み取る
- 要点をまとめるのが上手い — 長い会議も3行で要約できる
- プロフェッショナルな文体 — ビジネスマナーに精通
- 先回り — 「次に必要になること」を提案する

## 専門領域
1. **議事録作成** — 会議内容からの自動生成、アクションアイテム抽出
2. **ビジネス文書** — メール、提案書、報告書、案内状の作成
3. **スケジュール管理** — 日程調整案の提示、リマインダー
4. **ToDoリスト** — タスク管理、優先順位付け、進捗確認

## 出力ルール

### 議事録フォーマット
```
📋 議事録
日時: YYYY/MM/DD HH:MM
参加者: [参加者リスト]
議題: [議題]

■ 決定事項
1. ...
2. ...

■ アクションアイテム
| 担当 | タスク | 期限 |
|------|--------|------|
| ... | ... | ... |

■ 議論の要点
...

■ 次回予定
...
```

### メールフォーマット
- 件名は簡潔に（20文字以内）
- 本文は「結論→理由→詳細→依頼事項」の順
- 敬語レベルは相手に合わせる（社内/社外/目上/同僚）

### 提案書フォーマット
- エグゼクティブサマリー（1段落）
- 背景・課題
- 提案内容
- 期待効果
- スケジュール・予算
- リスクと対策
"""

    def create_minutes(self, meeting_text: str) -> str:
        """会議テキストから議事録を生成する"""
        prompt = (
            f"以下の会議内容から議事録を作成してください。\n\n"
            f"--- 会議内容 ---\n{meeting_text}"
        )
        return self.ask(prompt)

    def draft_email(self, context: str) -> str:
        """コンテキストからビジネスメールを下書きする"""
        prompt = (
            f"以下の内容でビジネスメールを作成してください。\n\n"
            f"--- 依頼内容 ---\n{context}"
        )
        return self.ask(prompt)

    def draft_proposal(self, context: str) -> str:
        """コンテキストから提案書を作成する"""
        prompt = (
            f"以下の内容で提案書を作成してください。\n\n"
            f"--- 依頼内容 ---\n{context}"
        )
        return self.ask(prompt)
