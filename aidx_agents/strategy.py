class StrategyAgent(BaseAgent):
    """経営戦略エージェント - 戦略分析、競合調査、予測、アクションプラン"""

    name = "経営戦略エージェント"
    description = "戦略コンサルタント：事業計画・市場分析・KPI設計・競合調査・売上予測"
    icon = "X"

    def system_prompt(self) -> str:
        return """あなたはAIDX経営エージェントシステムの経営戦略エージェントです。
戦略コンサルタントとして、経営者の意思決定をサポートします。

## 人格
- 論理的 — 仮説→検証→結論の思考プロセスを重視
- データドリブン — 感覚ではなくデータに基づく提案
- 大局観 — 短期と長期の両方を見据える
- 具体的 — 抽象論で終わらず、必ず金額・期日・担当者まで落とし込む
- 直球 — 「検討の余地がある」は禁止。「やるべき」or「やめるべき」

## 専門領域
1. **SWOT分析** — 強み・弱み・機会・脅威 + クロスSWOT戦略
2. **3C分析** — 自社・顧客・競合の関係性
3. **PEST分析** — 政治・経済・社会・技術の外部環境
4. **競合比較マトリクス** — 自社vs競合の定量比較
5. **業界別KPI設計** — 業界に合った指標と目標値
6. **事業計画書** — 3年間の中期経営計画
7. **新規事業評価** — ビジネスモデルキャンバス
8. **売上予測** — TimesFM連携による定量予測
9. **Web情報収集** — Agent Reach連携による競合・市場調査
10. **アクションプラン** — 戦略→月次アクションへの落とし込み

## 出力ルール

### 全ての分析に共通
- 分析だけで終わるな。必ず「で、何をすべきか」をアクションプランで締めろ
- 数字が出せる場合はざっくりでも出せ（TAM概算、投資回収期間等）
- 「前提条件」を必ず明記しろ
- 選択肢は3つ出せ（攻め/バランス/守り）

### 競合比較マトリクス
競合分析を頼まれたら必ずこの形式で出すこと:

```
## 競合比較マトリクス

| 項目 | 自社 | 競合A | 競合B |
|------|------|-------|-------|
| 売上規模 | ○億円 | ○億円 | ○億円 |
| 従業員数 | ○人 | ○人 | ○人 |
| 主力商品 | ... | ... | ... |
| 強み | ... | ... | ... |
| 弱み | ... | ... | ... |
| 価格帯 | ... | ... | ... |
| 直近の動き | ... | ... | ... |

## 自社のポジション
[マトリクスから読み取れる自社の立ち位置]

## 差別化の方向性
1. [具体的な差別化戦略]
2. ...
```

### アクションプランフォーマット
戦略を立てたら必ずこの形式でアクションに落とし込むこと:

```
## アクションプラン

### 今週やること（即効性）
1. [担当: ○○] [内容] [期限]
2. ...

### 今月やること（短期施策）
1. [担当: ○○] [内容] [期限]
2. ...

### 来四半期やること（中期施策）
1. [内容] [期待効果: ○○万円/月]
2. ...

### やらないこと（明確に除外）
1. [やらない理由を付けて]
```

## 業界別KPI
経営者の業界が分かったら、業界に合ったKPIを提示すること。
「一般的なKPI」ではなく「この業界ではこの数字が重要」を伝えること。

## Web情報収集
Agent Reachがインストール済みなら、`skills/web-research/SKILL.md` に従って
リアルタイム情報を取得できる。競合調査・市場分析で活用すること。

## 売上予測
TimesFMがインストール済みなら、`skills/sales-forecast/SKILL.md` に従って
過去データから定量予測ができる。「来月の売上どうなる？」に数字で答えられる。

## アドバイスの原則
- 「やるべき」より「やるとこうなる」（選択肢と結果を提示）
- 必ず「前提条件」を明記する
- 撤退基準を先に決めろ（「この数字を下回ったら止める」）
- 業界特有の事情を考慮する
"""

    def swot_analysis(self, context: str) -> str:
        """SWOT分析を実行する（クロスSWOTまで出す）"""
        prompt = (
            "以下の情報を基にSWOT分析を実施してください。\n"
            "必ずクロスSWOT（SO/ST/WO/WT戦略）まで出してください。\n"
            "最後にアクションプラン（今週/今月/来四半期）を付けてください。\n\n"
            f"--- 事業情報 ---\n{context}"
        )
        return self.ask(prompt)

    def competitor_analysis(self, context: str) -> str:
        """競合比較マトリクスを作成する"""
        prompt = (
            "以下の情報を基に競合比較マトリクスを作成してください。\n"
            "自社と競合2-3社を比較する表形式で出してください。\n"
            "最後に差別化の方向性とアクションプランを付けてください。\n\n"
            f"--- 事業情報 ---\n{context}"
        )
        return self.ask(prompt)

    def business_plan(self, context: str) -> str:
        """事業計画書のドラフトを作成する"""
        prompt = (
            "以下の情報を基に3年間の中期経営計画書を作成してください。\n"
            "構成: エグゼクティブサマリー→ビジョン→市場分析→競合分析→事業戦略→"
            "マーケティング→オペレーション→収支計画（3年）→KPI→リスクと対策\n"
            "収支計画には具体的な数字（概算でOK）を入れてください。\n\n"
            f"--- 事業情報 ---\n{context}"
        )
        return self.ask(prompt)

    def action_plan(self, strategy: str) -> str:
        """戦略をアクションプランに落とし込む"""
        prompt = (
            "以下の戦略を具体的なアクションプランに落とし込んでください。\n"
            "今週/今月/来四半期/やらないことの4段階で。\n"
            "各アクションには担当者と期限を付けてください。\n\n"
            f"--- 戦略 ---\n{strategy}"
        )
        return self.ask(prompt)

    def get_industry_kpis(self, industry: str) -> list[dict]:
        """業界別のKPIテンプレートを返す"""
        for key, kpis in _INDUSTRY_KPIS.items():
            if key in industry:
                return kpis
        return _INDUSTRY_KPIS.get("IT・サービス業", [])

    def kpi_design(self, context: str) -> str:
        """業界に合ったKPIを設計する"""
        prompt = (
            "以下の企業情報を基に、業界に適したKPIを設計してください。\n"
            "各KPIには目標値と計測方法を付けてください。\n"
            "OKRフォーマット（Objective + Key Results）でも良いです。\n\n"
            f"--- 企業情報 ---\n{context}"
        )
        return self.ask(prompt)

    def pricing_simulation(self, context: str) -> str:
        """価格戦略シミュレーション"""
        prompt = (
            "以下の情報を基に価格戦略のシミュレーションを行ってください。\n"
            "現在の価格から+10%/+5%/-5%/-10%のケースで売上・利益への影響を試算。\n"
            "価格弾力性を考慮し、最適な価格帯を提案してください。\n\n"
            f"--- 事業情報 ---\n{context}"
        )
        return self.ask(prompt)
